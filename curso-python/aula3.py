# Tipos str (strings)

print('Jamerson')  # Exemplo de string
print('Jamerson Marcondes')  
print('Jamerson "Marcondes"')  # Exemplo de string com aspas duplas dentro  

# Aspas simples e duplas podem ser usadas para definir strings

# Escape
print("Jamerson \"Marcondes\"")

# r
print(r"Jamerson \"Marcondes\"")  # Raw string